// Auto-escaping HTML templates. Every interpolation is escaped unless it is a SafeHtml value.
class SafeHtml {
  constructor(s) { this.s = s; }
  toString() { return this.s; }
}

export const esc = (v) =>
  String(v ?? '').replace(/[&<>"'`]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;', '`': '&#96;' })[c]);

function render(v) {
  if (v === null || v === undefined || v === false) return '';
  if (v instanceof SafeHtml) return v.s;
  if (Array.isArray(v)) return v.map(render).join('');
  return esc(v);
}

export function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i++) out += render(values[i]) + strings[i + 1];
  return new SafeHtml(out);
}

// Only for strings that are already known-safe HTML (e.g. generated by html``).
export const raw = (s) => new SafeHtml(String(s));

// JSON safe to embed inside <script type="application/json">.
export const jsonForScript = (obj) => raw(JSON.stringify(obj).replace(/</g, '\\u003c').replace(/>/g, '\\u003e').replace(/&/g, '\\u0026'));

// Minimal, safe "plain text with structure" renderer for admin-editable content:
// blank line = new paragraph, "## " heading, "- " bullet, **bold**, and [text](https://link).
export function richText(text) {
  const blocks = String(text || '').replace(/\r/g, '').split(/\n{2,}/);
  const inline = (s) =>
    esc(s)
      .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
      .replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+|\/[^\s)]*|mailto:[^\s)]+|tel:[^\s)]+)\)/g, (_m, t, u) => `<a href="${u}" rel="noopener">${t}</a>`);
  return raw(
    blocks
      .map((b) => {
        const lines = b.split('\n');
        if (lines.every((l) => l.startsWith('- '))) return `<ul>${lines.map((l) => `<li>${inline(l.slice(2))}</li>`).join('')}</ul>`;
        if (b.startsWith('## ')) return `<h2>${inline(b.slice(3))}</h2>`;
        if (b.startsWith('### ')) return `<h3>${inline(b.slice(4))}</h3>`;
        return `<p>${lines.map(inline).join('<br>')}</p>`;
      })
      .join('\n'),
  );
}
